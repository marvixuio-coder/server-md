function mathRiddles(n: number): Riddle[] {
  const out: Riddle[] = [];
  let seed = 7;
  const rnd = (m: number) => ((seed = (seed * 9301 + 49297) % 233280), Math.floor((seed / 233280) * m));
  for (let k = 0; k < n; k++) {
    const a = rnd(20) + 2;
    const b = rnd(12) + 2;
    const t = k % 4;
    if (t === 0) out.push({ q: `كم ناتج ${a} × ${b}؟`, a: [String(a * b)] });
    else if (t === 1) out.push({ q: `كم ناتج ${a * 7} + ${b * 9}؟`, a: [String(a * 7 + b * 9)] });
    else if (t === 2) out.push({ q: `كم ناتج ${a * b} ÷ ${b}؟`, a: [String(a)] });
    else out.push({ q: `معك ${a * 5} ريال وصرفت ${b * 3}، كم بقي معك؟`, a: [String(a * 5 - b * 3)] });
  }
  return out;
}

